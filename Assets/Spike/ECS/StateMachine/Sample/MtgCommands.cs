#nullable enable
using StateMachine.Engine;

namespace StateMachine.Sample
{
    /// <summary>The "I'm done with this state" marker. Pass is what completes
    /// most non-decision states.</summary>
    public sealed record PassCommand : GameAction;

    /// <summary>Player input during DeclareAttackers. Toggles IsAttacking on
    /// a creature — the *whole* selection is read off entities, not stored
    /// on the state record.</summary>
    public sealed record ToggleAttackerCommand(long CardId) : GameAction;

    /// <summary>"I'm done picking attackers" — what completes DeclareAttackers.</summary>
    public sealed record CommitAttackersCommand : GameAction;

    /// <summary>"I'm done picking blockers" — what completes DeclareBlockers.</summary>
    public sealed record CommitBlockersCommand : GameAction;

    /// <summary>Generated by CombatDamageState.OnEnter, one per attacker.</summary>
    public sealed record DealDamageCommand(long SourceId, int Amount) : GameAction;

    /// <summary>Generated by EndState.OnEnter. Clears every entity's tag of
    /// the given key — the spike's ClearTagsCommand&lt;T&gt; shape.</summary>
    public sealed record ClearTagCommand(string TagName) : GameAction;

    /// <summary>EndState.OnEnter generator. Match singleton mutation —
    /// concrete proof that "would-be state data" lives on Match, not on the
    /// state record.</summary>
    public sealed record IncrementTurnCommand : GameAction;
    public sealed record SwapActivePlayerCommand : GameAction;

    /// <summary>UpkeepState.OnEnter generators. Bodies are no-ops for this
    /// spike — what matters is that they get enqueued by the push handler
    /// and land as events, not what they actually do.</summary>
    public sealed record UntapAllCommand : GameAction;
    public sealed record DrawCardCommand(PlayerId Player) : GameAction;

    public sealed record StandardResult : CommandResult
    {
        public static readonly StandardResult Instance = new();
    }
}
